inline void writeTabEntry(uint8_t *tab, size_t idx, uint32_t offset, uint8_t w, uint8_t h) {
    tab[idx * 6 + 0] = static_cast<uint8_t>(offset & 0xFF);
    tab[idx * 6 + 1] = static_cast<uint8_t>((offset >> 8) & 0xFF);
    tab[idx * 6 + 2] = static_cast<uint8_t>((offset >> 16) & 0xFF);
    tab[idx * 6 + 3] = static_cast<uint8_t>((offset >> 24) & 0xFF);
    tab[idx * 6 + 4] = w;
    tab[idx * 6 + 5] = h;
}

inline void patchWeaponSprites(bool isMenuSprites, uint8_t *&tabData, size_t &tabSize, uint8_t *&data, size_t &size) {
    if (!tabData || !data) return;
    if (isMenuSprites && tabSize >= 1180 * 6) {
        size_t newTabCount = (tabSize / 6 < 1181) ? 1181 : (tabSize / 6);
        size_t newTabSize = newTabCount * 6;
        uint8_t *newTab = new uint8_t[newTabSize];
        std::memset(newTab, 0, newTabSize);
        std::memcpy(newTab, tabData, tabSize);

        size_t extraBytes = sizeof(kBaseMsprPistolSmall) + sizeof(kBaseMsprPistolBig) +
                            sizeof(kBaseMsprAccessCardSmall) + sizeof(kBaseMsprAccessCardBig) +
                            sizeof(kArMsprAirStrikeSmall) + sizeof(kArMsprAirStrikeBig) +
                            sizeof(kArMsprCloneShieldSmall) + sizeof(kArMsprCloneShieldBig);
        uint8_t *newData = new uint8_t[size + extraBytes];
        std::memcpy(newData, data, size);
        uint32_t curOff = static_cast<uint32_t>(size);

        auto appendSpr = [&](size_t idx, const uint8_t *bytes, size_t len, uint8_t w, uint8_t h) {
            std::memcpy(newData + curOff, bytes, len);
            writeTabEntry(newTab, idx, curOff, w, h);
            curOff += static_cast<uint32_t>(len);
        };

        appendSpr(15, kBaseMsprPistolSmall, sizeof(kBaseMsprPistolSmall), 16, 16);
        appendSpr(65, kBaseMsprPistolBig, sizeof(kBaseMsprPistolBig), 62, 43);
        appendSpr(26, kBaseMsprAccessCardSmall, sizeof(kBaseMsprAccessCardSmall), 16, 16);
        appendSpr(76, kBaseMsprAccessCardBig, sizeof(kBaseMsprAccessCardBig), 62, 43);
        appendSpr(27, kArMsprAirStrikeSmall, sizeof(kArMsprAirStrikeSmall), 16, 16);
        appendSpr(1180, kArMsprAirStrikeBig, sizeof(kArMsprAirStrikeBig), 62, 43);
        appendSpr(29, kArMsprCloneShieldSmall, sizeof(kArMsprCloneShieldSmall), 16, 16);
        appendSpr(83, kArMsprCloneShieldBig, sizeof(kArMsprCloneShieldBig), 62, 43);

        delete[] tabData;
        delete[] data;
        tabData = newTab;
        tabSize = newTabSize;
        data = newData;
        size = curOff;
    } else if (!isMenuSprites && tabSize >= 1658 * 6) {
        size_t extraBytes = 8 * 640;
        uint8_t *newData = new uint8_t[size + extraBytes];
        std::memcpy(newData, data, size);
        uint32_t curOff = static_cast<uint32_t>(size);

        auto appendSpr = [&](size_t idx, const uint8_t *bytes, size_t len, uint8_t w, uint8_t h) {
            std::memcpy(newData + curOff, bytes, len);
            writeTabEntry(tabData, idx, curOff, w, h);
            curOff += static_cast<uint32_t>(len);
        };

        appendSpr(1603, kBaseHsprPistolUnsel, sizeof(kBaseHsprPistolUnsel), 32, 32);
        appendSpr(1643, kBaseHsprPistolSel, sizeof(kBaseHsprPistolSel), 32, 32);
        appendSpr(1614, kBaseHsprAccessCardUnsel, sizeof(kBaseHsprAccessCardUnsel), 32, 32);
        appendSpr(1654, kBaseHsprAccessCardSel, sizeof(kBaseHsprAccessCardSel), 32, 32);
        appendSpr(1615, kArHsprAirStrikeUnsel, sizeof(kArHsprAirStrikeUnsel), 32, 32);
        appendSpr(1655, kArHsprAirStrikeSel, sizeof(kArHsprAirStrikeSel), 32, 32);
        appendSpr(1617, kArHsprCloneShieldUnsel, sizeof(kArHsprCloneShieldUnsel), 32, 32);
        appendSpr(1657, kArHsprCloneShieldSel, sizeof(kArHsprCloneShieldSel), 32, 32);

        delete[] data;
        data = newData;
        size = curOff;
    }
}

